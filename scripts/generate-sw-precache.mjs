import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const appDir = path.join(rootDir, 'app');
const publicSwPath = path.join(rootDir, 'public', 'sw.js');
const precacheManifestPath = path.join(rootDir, 'lib', 'offline', 'precacheRoutes.ts');

const DEFAULT_STATIC_ASSETS = [
  '/',
  '/icon.svg',
  '/theme-init.js',
  '/globals.css',
];

const CIPHER_SUBSTITUTES = [
  'caesar',
  'rot13',
  'vigenere',
  'des',
  'aes',
  'rsa',
  'sha256',
  'bcrypt',
];

function getRoutesFromDir(dir, baseRoute = '') {
  const routes = [];
  if (!fs.existsSync(dir)) return routes;

  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    if (entry.isDirectory()) {
      const folderName = entry.name;
      const fullPath = path.join(dir, folderName);

      if (folderName.startsWith('(') && folderName.endsWith(')')) {
        // Route group folder, pass through baseRoute
        routes.push(...getRoutesFromDir(fullPath, baseRoute));
      } else if (folderName.startsWith('[') && folderName.endsWith(']')) {
        // Dynamic route parameter
        for (const cipherId of CIPHER_SUBSTITUTES) {
          const route = `${baseRoute}/${cipherId}/`;
          routes.push(route);
        }
      } else {
        const route = `${baseRoute}/${folderName}`;
        if (fs.existsSync(path.join(fullPath, 'page.tsx')) || fs.existsSync(path.join(fullPath, 'page.js'))) {
          routes.push(`${route}/`);
        }
        routes.push(...getRoutesFromDir(fullPath, route));
      }
    }
  }

  return routes;
}

export function generatePrecacheList() {
  const discoveredRoutes = getRoutesFromDir(appDir);
  const routeSet = new Set([...DEFAULT_STATIC_ASSETS, ...discoveredRoutes]);
  
  // Clean up routes and ensure unique formatting
  const formattedRoutes = Array.from(routeSet)
    .map(r => r.replace(/\/+/g, '/'))
    .sort();

  return formattedRoutes;
}

export function buildServiceWorker() {
  const precacheUrls = generatePrecacheList();
  const buildTimestamp = new Date().toISOString();
  const cacheVersion = `cryptoviz-v${Date.now()}`;

  const swContent = `/**
 * CryptoViz Service Worker (Auto-Generated Precache)
 * Last Generated: ${buildTimestamp}
 * 
 * NOTE: This file is automatically generated by scripts/generate-sw-precache.mjs during build.
 * To update precached routes manually, run: npm run generate:sw or modify scripts/generate-sw-precache.mjs.
 */

const CACHE_NAME = '${cacheVersion}';
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => {
      return cache.addAll(PRECACHE_URLS).catch(err => console.warn('Pre-cache item warning:', err));
    }).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(cacheNames => {
      return Promise.all(
        cacheNames.map(name => {
          if (name !== CACHE_NAME && name.startsWith('cryptoviz-')) {
            return caches.delete(name);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;

  event.respondWith(
    caches.match(event.request).then(cachedResponse => {
      if (cachedResponse) {
        return cachedResponse;
      }
      return fetch(event.request)
        .then(networkResponse => {
          if (!networkResponse || networkResponse.status !== 200 || networkResponse.type !== 'basic') {
            return networkResponse;
          }
          const responseToCache = networkResponse.clone();
          caches.open(CACHE_NAME).then(cache => {
            cache.put(event.request, responseToCache);
          });
          return networkResponse;
        })
        .catch(() => {
          if (event.request.mode === 'navigate') {
            return caches.match('/offline/') || caches.match('/offline') || caches.match('/');
          }
        });
    })
  );
});
`;

  fs.writeFileSync(publicSwPath, swContent, 'utf8');

  // Also write exported TypeScript precache list for client modules (e.g. swRegister.ts)
  const manifestContent = `/**
 * Auto-generated precache routes manifest.
 * Last Generated: ${buildTimestamp}
 */
export const PRECACHE_ROUTES: string[] = ${JSON.stringify(precacheUrls, null, 2)};
`;

  fs.writeFileSync(precacheManifestPath, manifestContent, 'utf8');
  console.log(`[generate-sw] Service worker successfully written to public/sw.js with ${precacheUrls.length} precached URLs.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  buildServiceWorker();
}
